/**
 * Android release configuration for Lueur (applied at `expo prebuild`).
 *
 * 1. Release signing from Gradle properties (~/.gradle/gradle.properties or
 *    -P flags / ORG_GRADLE_PROJECT_* env vars in CI):
 *      LUEUR_UPLOAD_STORE_FILE, LUEUR_UPLOAD_STORE_PASSWORD,
 *      LUEUR_UPLOAD_KEY_ALIAS, LUEUR_UPLOAD_KEY_PASSWORD
 *    Without them the release build falls back to the debug key (local testing only).
 * 2. Removes the INTERNET permission from the release manifest only: debug
 *    builds still need it to reach the Metro bundler.
 */
const { withAppBuildGradle, withDangerousMod } = require('expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

const SIGNING_BLOCK = `
        release {
            if (project.hasProperty('LUEUR_UPLOAD_STORE_FILE')) {
                storeFile file(LUEUR_UPLOAD_STORE_FILE)
                storePassword LUEUR_UPLOAD_STORE_PASSWORD
                keyAlias LUEUR_UPLOAD_KEY_ALIAS
                keyPassword LUEUR_UPLOAD_KEY_PASSWORD
            }
        }`;

function withReleaseSigning(config) {
  return withAppBuildGradle(config, (cfg) => {
    let src = cfg.modResults.contents;
    if (!src.includes('LUEUR_UPLOAD_STORE_FILE')) {
      src = src.replace(/signingConfigs\s*\{/, (m) => `${m}${SIGNING_BLOCK}`);
      src = src.replace(
        /(buildTypes\s*\{[\s\S]*?release\s*\{[\s\S]*?)signingConfig\s+signingConfigs\.debug/,
        `$1signingConfig project.hasProperty('LUEUR_UPLOAD_STORE_FILE') ? signingConfigs.release : signingConfigs.debug`,
      );
    }
    cfg.modResults.contents = src;
    return cfg;
  });
}

const RELEASE_MANIFEST = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-android-release.js: Lueur makes no network requests. -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:tools="http://schemas.android.com/tools">
    <uses-permission android:name="android.permission.INTERNET" tools:node="remove" />
    <uses-permission android:name="android.permission.ACCESS_NETWORK_STATE" tools:node="remove" />
    <uses-permission android:name="android.permission.ACCESS_WIFI_STATE" tools:node="remove" />
</manifest>
`;

function withReleaseManifest(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'release');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'AndroidManifest.xml'), RELEASE_MANIFEST);
      return cfg;
    },
  ]);
}

module.exports = function withAndroidRelease(config) {
  return withReleaseManifest(withReleaseSigning(config));
};
